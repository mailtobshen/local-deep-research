    @staticmethod
    def _wrap_footer(footer_inner_xml: str) -> str:
        """Wrap the footer inner XML in the required ``<w:ftr>`` root."""
        return (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            f'<w:ftr xmlns:w="{_W_NS}">'
            f'{footer_inner_xml}'
            '</w:ftr>'
        )

    @classmethod
    def _inject_footer_into_docx(
        cls, docx_bytes: bytes, query: Optional[str] = None
    ) -> bytes:
        """Return a copy of the DOCX with the post-processing done.

        Three concerns the user asked us to address live here, because
        Pandoc cannot express them through raw markdown:

          1. The Chinese page-number footer (``第N页/共M页``) is
             injected as ``word/footer1.xml`` with real OOXML PAGE /
             NUMPAGES field codes — Word/LibreOffice update the
             numbers on open.
          2. The report title (``关于{query}的研究报告``) is injected
             as a styled ``<w:p>`` at the very top of ``<w:body>``
             so it is the *only* title (the report itself starts with
             ``# 目录`` and would otherwise produce two visible titles).
             二号 (22pt) 黑体, bold, centred, black.
          3. The default body font/size in ``word/styles.xml`` is set
             to 宋体 (SimSun) 五号 (10.5pt = 21 half-points), and
             ``w:themeFontLang``/``w:rPrDefault`` are wired so Word
             uses this for unstyled body text. Heading styles are
             left untouched so chapter heading sizes are unchanged.

        Algorithm:
          1. Unzip the DOCX into memory.
          2. If ``word/footer1.xml`` doesn't exist, create it with
             our page-number XML.
          3. Ensure ``word/_rels/document.xml.rels`` carries a
             relationship to ``footer1.xml`` with a stable Id.
          4. Ensure ``[Content_Types].xml`` declares the footer part.
          5. Ensure each ``<w:sectPr>`` in ``word/document.xml``
             references the footer relationship.
          6. Inject the title paragraph at the very top of
             ``<w:body>`` (only if ``query`` is provided).
          7. Patch ``word/styles.xml`` so the body default is 宋体 五号.

        Idempotent: re-running on an already-patched DOCX keeps the
        existing footer instead of duplicating it.
        """
        if not docx_bytes:
            return docx_bytes

        footer_xml = cls._wrap_footer(cls._build_footer_xml())
        title_para_xml = (
            cls._build_title_paragraph_xml(query) if query else None
        )
        footer_rid = "rIdLdrFooter"

        # Read everything into memory up front — DOCX files are small.
        src_zip = zipfile.ZipFile(io.BytesIO(docx_bytes), "r")
        names_to_data = {name: src_zip.read(name) for name in src_zip.namelist()}
        src_zip.close()

        # 1) Write footer1.xml (overwrite if present, create if not).
        names_to_data["word/footer1.xml"] = footer_xml.encode("utf-8")

        # 2) Update word/_rels/document.xml.rels so the footer part is
        #    discoverable by document.xml.
        rels_path = "word/_rels/document.xml.rels"
        rels_xml = names_to_data.get(rels_path, b"").decode("utf-8") if rels_path in names_to_data else ""
        if rels_xml and 'Target="footer1.xml"' not in rels_xml:
            # Insert the footer relationship before </Relationships>.
            new_rel = (
                f'<Relationship Id="{footer_rid}" '
                'Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/footer" '
                'Target="footer1.xml"/>'
            )
            rels_xml = rels_xml.replace(
                "</Relationships>", new_rel + "</Relationships>", 1
            )
            names_to_data[rels_path] = rels_xml.encode("utf-8")
        elif not rels_xml:
            # No rels file at all — minimal valid one.
            rels_xml = (
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
                '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
                + f'<Relationship Id="{footer_rid}" '
                'Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/footer" '
                'Target="footer1.xml"/>'
                + "</Relationships>"
            )
            names_to_data[rels_path] = rels_xml.encode("utf-8")

        # 3) Update [Content_Types].xml so the footer part is declared.
        ct_path = "[Content_Types].xml"
        ct_xml = (
            names_to_data[ct_path].decode("utf-8")
            if ct_path in names_to_data
            else ""
        )
        if ct_xml and 'PartName="/word/footer1.xml"' not in ct_xml:
            override = (
                '<Override PartName="/word/footer1.xml" '
                'ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.footer+xml"/>'
            )
            ct_xml = ct_xml.replace("</Types>", override + "</Types>", 1)
            names_to_data[ct_path] = ct_xml.encode("utf-8")
        elif not ct_xml:
            ct_xml = (
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
                '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
                '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
                '<Default Extension="xml" ContentType="application/xml"/>'
                '<Override PartName="/word/document.xml" '
                'ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>'
                '<Override PartName="/word/footer1.xml" '
                'ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.footer+xml"/>'
                '</Types>'
            )
            names_to_data[ct_path] = ct_xml.encode("utf-8")

        # 4) Update every <w:sectPr> in word/document.xml to reference
        #    our footer relationship. Word renders the footer on every
        #    page in the section.
        doc_path = "word/document.xml"
        doc_xml = (
            names_to_data[doc_path].decode("utf-8")
            if doc_path in names_to_data
            else ""
        )
        if doc_xml and f'r:id="{footer_rid}"' not in doc_xml:
            # Find every <w:sectPr ...> ... </w:sectPr> block and
            # ensure it carries a <w:footerReference w:type="default"
            # r:id="..."/> child. If the block already has one, replace
            # the r:id. Otherwise insert one as the first child.
            def patch_sectpr(match: "re.Match[str]") -> str:
                block = match.group(0)
                if "footerReference" in block and f'r:id="{footer_rid}"' in block:
                    return block
                new_ref = (
                    f'<w:footerReference w:type="default" r:id="{footer_rid}"/>'
                )
                if "footerReference" in block:
                    # Replace the first existing footerReference's r:id.
                    return re.sub(
                        r'<w:footerReference[^/]*r:id="[^"]*"[^/]*/>',
                        new_ref,
                        block,
                        count=1,
                    )
                # Insert as the first child of sectPr.
                # Find the opening tag's closing >.
                open_tag_end = block.find(">") + 1
                return block[:open_tag_end] + new_ref + block[open_tag_end:]

            doc_xml = re.sub(
                r"<w:sectPr\b[^>]*>.*?</w:sectPr>",
                patch_sectpr,
                doc_xml,
                flags=re.DOTALL,
            )
            # Self-closing <w:sectPr .../> form (Pandoc occasionally emits
            # this for the final section).
            def patch_selfclosing_sectpr(match: "re.Match[str]") -> str:
                attrs = match.group(1)
                return (
                    f"<w:sectPr{attrs}>"
                    f'<w:footerReference w:type="default" r:id="{footer_rid}"/>'
                    "</w:sectPr>"
                )
            doc_xml = re.sub(
                r"<w:sectPr\b([^>]*)/>",
                patch_selfclosing_sectpr,
                doc_xml,
            )
            names_to_data[doc_path] = doc_xml.encode("utf-8")

        # 6) Inject the title paragraph at the very top of <w:body>.
        if title_para_xml and doc_path in names_to_data:
            doc_xml = names_to_data[doc_path].decode("utf-8")
            # Insert the title paragraph right after <w:body> opens,
            # before any existing body content. Idempotent: skip if a
            # title with the same text is already present.
            if not cls._title_already_present(doc_xml, title_para_xml):
                doc_xml = re.sub(
                    r"(<w:body[^>]*>)",
                    lambda m: m.group(1) + title_para_xml,
                    doc_xml,
                    count=1,
                )
                names_to_data[doc_path] = doc_xml.encode("utf-8")

        # 7) Patch word/styles.xml: body default 宋体 五号, heading
        #    styles 楷体 (sizes unchanged). Body font and heading
        #    font are independent patches — order doesn't matter
        #    because each touches a disjoint rPr block.
        names_to_data = cls._set_default_body_font(names_to_data)
        names_to_data = cls._patch_styles_xml_kaiti_headings(names_to_data)

        # 8) Strip the heading style from any body paragraph that
        #    contains the query text. LLM chapters often open with
        #    ``# <query>`` which would otherwise render as a second
        #    "title" next to the user-requested title injected in
        #    step 6. We drop just the pStyle so the heading text
        #    stays in the document but renders as ordinary body text.
        if query:
            names_to_data = cls._strip_query_heading_style(
                names_to_data, query
            )

        # Write the new zip back out.
        out_buf = io.BytesIO()
        with zipfile.ZipFile(out_buf, "w", zipfile.ZIP_DEFLATED) as dst_zip:
            for name, data in names_to_data.items():
                dst_zip.writestr(name, data)
        return out_buf.getvalue()

