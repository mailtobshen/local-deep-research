    # Markdown → DOCX
    # ------------------------------------------------------------------

    def export(
        self,
        markdown_content: str,
        options: Optional[ExportOptions] = None,
    ) -> ExportResult:
        """Convert markdown content to DOCX.

        Flow:
          1. Prepend the "关于{query}的研究报告" title (if query given).
          2. Scrub the old "Generated by LDR..." body footer.
          3. Run Pandoc markdown → DOCX, with ``--resource-path`` set to
             the request's base_url so the rewritten
             ``/images/<research_id>/<filename>`` routes resolve.
          4. Post-process the resulting DOCX zip to inject the
             Chinese page-number footer.

        Args:
            markdown_content: The markdown text to convert
            options: Optional export options (title, metadata, base_url,
                trusted_hosts, query)

        Returns:
            ExportResult with DOCX content as bytes, filename, mimetype

        Raises:
            RuntimeError: If pypandoc is missing or Pandoc fails.
        """
        if not PYPANDOC_AVAILABLE:
            raise RuntimeError(
                "DOCX export requires pypandoc. Install with: pip install pypandoc-binary"
            )

        try:
            self._validate_content_size(markdown_content)

            options = options or ExportOptions()

            # 1) Pre-process: scrub horizontal rules, fix the TOC
            #    formatting, rewrite relative image URLs to absolute
            #    under base_url. The title text itself is NOT added
            #    here — it is injected as a styled OOXML paragraph by
            #    the post-processor (a markdown H1 would produce a
            #    duplicate title alongside the report's existing
            #    ``# 目录`` first heading).
            markdown_content = self._prepare_markdown(
                markdown_content, options.query, options.base_url
            )
            # 2) Scrub the old LDR body footer (defence in depth —
            #    older reports in the DB might still carry it).
            markdown_content = self._scrub_body(markdown_content)

            # Build pandoc args for metadata (sanitized).
            extra_args = []
            if options.title:
                safe_title = self._sanitize_metadata(options.title)
                extra_args.append(f"--metadata=title:{safe_title}")
            if options.metadata:
                if options.metadata.get("author"):
                    safe_author = self._sanitize_metadata(
                        options.metadata["author"]
                    )
                    extra_args.append(f"--metadata=author:{safe_author}")
                if options.metadata.get("date"):
                    safe_date = self._sanitize_metadata(
                        options.metadata["date"]
                    )
                    extra_args.append(f"--metadata=date:{safe_date}")

            # Tell Pandoc where to resolve relative image URLs against.
            # This is the DOCX-path equivalent of WeasyPrint's base_url.
            # ``/images/<research_id>/<filename>`` rewritten by
            # ``images.store.rewrite_markdown`` becomes
            # ``<base_url>images/<research_id>/<filename>`` here, which
            # is exactly the URL the same Flask app serves.
            if options.base_url:
                extra_args.append(
                    f"--resource-path={self._sanitize_metadata(options.base_url)}"
                )

            # Convert in memory: pipe markdown via stdin, capture DOCX
            # bytes from stdout.
            pandoc_path = pypandoc.get_pandoc_path()
            cmd = [pandoc_path, "-f", "markdown", "-t", "docx", "-o", "-"]
            cmd.extend(extra_args)

            # 30 s timeout matches the PDFService guidance. A slow
            # network image fetch inside the DOCX post-process path
            # (``--resource-path`` triggers HTTP GETs for every image
            # reference) can otherwise pin the export worker
            # indefinitely; the user gets a clear PandocTimeout
            # error instead of a hang.
            result = subprocess.run(
                cmd,
                input=markdown_content.encode("utf-8"),
                capture_output=True,
                check=True,
                timeout=30,
            )

            docx_bytes = result.stdout

            if not docx_bytes:
                raise RuntimeError(  # noqa: TRY301 — except only adds logging before re-raise
                    "Pandoc conversion failed - no output produced"
                )

            # 3) Post-process: inject the Chinese page-number footer.
            docx_bytes = self._inject_footer_into_docx(docx_bytes, query=options.query)

            filename = self._generate_safe_filename(options.title)

            logger.info(
                f"Generated DOCX in memory, size: {len(docx_bytes)} bytes"
            )

            return ExportResult(
                content=docx_bytes,
                filename=filename,
                mimetype=self.mimetype,
            )

        except subprocess.CalledProcessError as e:
            stderr = (
                e.stderr.decode("utf-8", errors="replace")
                if e.stderr
                else "unknown error"
            )
            logger.exception(f"Pandoc conversion failed: {stderr}")
            raise RuntimeError(f"Pandoc conversion failed: {stderr}") from e
        except Exception:
            logger.exception("Error generating DOCX")
            raise

    # ------------------------------------------------------------------
    # Metadata sanitisation (security: pandoc argument injection)
    # ------------------------------------------------------------------

    def _sanitize_metadata(self, value: str) -> str:
        """Sanitize metadata value to prevent argument injection.

        Removes potential pandoc argument injection patterns from
        user-supplied metadata values. Zero prior direct test coverage.
        """
        if not isinstance(value, str):
            return str(value)

        # Remove leading dashes (prevents --flag injection).
        result = value.lstrip("-")

        # Replace newlines with spaces (prevents multi-line injection).
        # Tabs are preserved — the original ODT sanitizer kept them
        # and downstream consumers may rely on them for tabular data.
        result = result.replace("\n", " ").replace("\r", " ")

        # Collapse any leading multiple-dashes that might remain.
        while result.startswith("--"):
            result = result[1:]

        # Strip all remaining double-dash sequences.
        result = result.replace("--", "")

        return result.strip()
